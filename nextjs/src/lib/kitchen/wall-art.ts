/**
 * The kitchen wall, drawn in code (issue #748). Ported from the "Shared pixel
 * scene" board of the Kitchen Home canvas (KitchenScene, viewBox 0 0 96 80, a
 * 16 px design grid at 1x = 1 unit per source pixel).
 *
 * Each entry is [fill, layer, rects]: one `fill` colour, the `layer` it
 * belongs to, and its rects as "x,y,w,h" strings in scene units. Entries are in
 * the board's own paint order, so rendering them in sequence reproduces it.
 *
 * Layers:
 *  - `base`: the room itself: wall, stripes, floor, lamp, window, curtains,
 *    plank, counter, stove with its pot, worktop clutter, the empty basket,
 *    the fridge and freezer shells, the door and its chalkboard. Always drawn.
 *  - `herbs`, `fridge`, `freezer`, `shelves`, `basket`: the static stock the
 *    board draws in each place (herb pot, milk and cheese, frozen bags, jars,
 *    apples). Drawn only when that place has items, so a first-visit kitchen
 *    matches the board's empty state (A5). The sprites ticket (issue #751)
 *    replaces these with per-category sprites.
 *
 * Colours: `var(--wall-*)` fills are the wall palette (see `WallPalette` in
 * `themes.ts`), so a kitchen theme recolours the room. Literal hex fills are
 * the colours of things that do not change with the theme (food, wood, steel).
 * The board's pixel Bubbles is not here: the pixel Bubbles ticket (issue #752)
 * draws it into the scene's floor layer.
 *
 * Generated from the board once and then edited by hand; there is no build step.
 */
