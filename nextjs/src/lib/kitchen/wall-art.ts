/** An SVG path `d` that fills every rect in a "x,y,w,h x,y,w,h" string. */
export function rectsToPath(rects: string): string {
  return rects
    .split(' ')
    .map((r) => {
      const [x, y, w, h] = r.split(',')
      return `M${x} ${y}h${w}v${h}h-${w}z`
    })
    .join('')
}
